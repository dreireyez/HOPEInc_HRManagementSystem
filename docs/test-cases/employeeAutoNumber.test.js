import { describe, it, expect, vi, beforeEach } from 'vitest';

vi.mock('../../src/lib/supabaseClient.js', () => ({
  default: { from: vi.fn() },
}));

import supabase from '../../src/lib/supabaseClient.js';
import { getNextEmpNo } from '../../src/services/employeeService.js';

const makeSelectChain = (result) => ({
  select: vi.fn().mockResolvedValue(result),
  eq: vi.fn().mockReturnThis(),
  then: (resolve) => resolve(result),
});

describe('employee auto-number generation', () => {
  beforeEach(() => vi.clearAllMocks());

  describe('getNextEmpNo', () => {
    it('returns a zero-padded 5-character string', async () => {
      const chain = makeSelectChain({ data: [{ empno: '00032' }], error: null });
      supabase.from.mockReturnValue(chain);

      const { data, error } = await getNextEmpNo();

      expect(error).toBeNull();
      expect(typeof data).toBe('string');
      expect(data).toHaveLength(5);
      expect(data).toBe('00033');
    });

    it('increments the current max empno by 1', async () => {
      const chain = makeSelectChain({ data: [{ empno: '00010' }, { empno: '00015' }, { empno: '00003' }], error: null });
      supabase.from.mockReturnValue(chain);

      const { data } = await getNextEmpNo();

      expect(data).toBe('00016');
    });

    it('returns 00001 when the employee table is empty', async () => {
      const chain = makeSelectChain({ data: [], error: null });
      supabase.from.mockReturnValue(chain);

      const { data, error } = await getNextEmpNo();

      expect(error).toBeNull();
      expect(data).toBe('00001');
    });

    it('zero-pads single digit results correctly', async () => {
      const chain = makeSelectChain({ data: [{ empno: '00004' }], error: null });
      supabase.from.mockReturnValue(chain);

      const { data } = await getNextEmpNo();

      expect(data).toBe('00005');
      expect(data).toHaveLength(5);
      expect(data.startsWith('0000')).toBe(true);
    });

    it('ignores non-numeric empno values when computing max', async () => {
      const chain = makeSelectChain({
        data: [{ empno: '00005' }, { empno: 'XXXXX' }, { empno: '00010' }],
        error: null,
      });
      supabase.from.mockReturnValue(chain);

      const { data } = await getNextEmpNo();

      expect(data).toBe('00011');
    });

    it('returns error when supabase fails', async () => {
      const chain = makeSelectChain({ data: null, error: new Error('connection refused') });
      supabase.from.mockReturnValue(chain);

      const { data, error } = await getNextEmpNo();

      expect(data).toBeNull();
      expect(error).toBeTruthy();
    });

    it('queries the employee table with lowercase column name', async () => {
      const chain = makeSelectChain({ data: [{ empno: '00001' }], error: null });
      supabase.from.mockReturnValue(chain);

      await getNextEmpNo();

      expect(supabase.from).toHaveBeenCalledWith('employee');
      expect(chain.select).toHaveBeenCalledWith('empno');
    });
  });

  describe('empno field must not accept manual input', () => {
    it('auto-generated empno must not equal a user-typed override', () => {
      const autoGenerated = '00033';
      const userTypedOverride = 'CUSTOM-001';

      // The field is disabled — user input must not be accepted.
      // This logic mirrors the disabled input in AddEmployeeModal.
      const resolvedEmpno = (disabled, autoValue, userValue) =>
        disabled ? autoValue : userValue;

      const result = resolvedEmpno(true, autoGenerated, userTypedOverride);

      expect(result).toBe(autoGenerated);
      expect(result).not.toBe(userTypedOverride);
    });

    it('submit payload contains auto-generated empno', () => {
      const autoEmpno = '00033';
      const buildPayload = (empno, firstname, lastname, gender) => ({
        empno,
        firstname,
        lastname,
        gender,
        record_status: 'ACTIVE',
      });

      const payload = buildPayload(autoEmpno, 'Jane', 'Doe', 'F');

      expect(payload).toHaveProperty('empno', '00033');
      expect(payload).not.toHaveProperty('email');
      expect(payload).not.toHaveProperty('job_title');
      expect(payload).not.toHaveProperty('dept');
    });

    it('submit payload does not include email column', () => {
      const buildPayload = (empno, firstname, lastname, gender, hiredate, birthdate) => ({
        empno,
        firstname,
        lastname,
        gender,
        hiredate: hiredate || null,
        birthdate: birthdate || null,
        record_status: 'ACTIVE',
      });

      const payload = buildPayload('00033', 'Jane', 'Doe', 'F', '2024-01-15', '1990-05-01');

      expect(Object.keys(payload)).not.toContain('email');
      expect(payload.record_status).toBe('ACTIVE');
    });
  });
});
